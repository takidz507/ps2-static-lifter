/*
 * host_real_runner.c — Milestone 2.2 Execution Harness for Lifted `hello_real.elf`
 * ================================================================================
 * Executes the lifted R5900 code of `hello_real.elf` (`lifted_hello_real.c`, 437 functions,
 * 30,060/30,090 lifted instructions) from its true ELF entry point (`0x00100b20`,
 * `fn_00100b20___start`) through `crt0`, `_main` (`0x00100000`), `_InitSys`, `_libcglue_init`,
 * `_init` (`.ctors`), `main` (`0x0011d540`), `puts("Hello world!")` -> newlib -> fdman ->
 * `fioWrite` -> SIF RPC `FILEIO`, `_fini` (`.dtors`), `_libcglue_deinit`, and `Exit(0)`
 * (`KExit` `syscall 0x04` at `0x001010f4`).
 *
 * Strictly adheres to all Milestone 2.2 rules:
 *   - No manual edits to `lifted_hello_real.c` (100% auto-generated by `ps2_lifter_m2.py`).
 *   - Starts at `fn_00100b20___start` (`0x00100b20`), never bypassing `crt0` or jumping to `main`.
 *   - Never calls host `printf` to synthesize guest output; the 13 bytes `"Hello world!\n"`
 *     come exclusively from the guest's own `.rodata` (`0x0011eba0`) -> newlib stdout buffer ->
 *     `fioWrite` -> SIF DMA `FIO_F_WRITE` packet in Guest RAM.
 *   - Records every syscall, indirect call, and SIF/IOP DMA boundary event into
 *     `syscall_trace.log` and `syscall_trace.json`, and writes the full execution state and
 *     100-PC ring buffer to `execution_state.log`.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <inttypes.h>
#include "ps2_runtime.h"
#include "lifted_hello_real.h"

int main(int argc, char **argv) {
    const char *trace_log_path  = "syscall_trace.log";
    const char *trace_json_path = "syscall_trace.json";
    const char *state_log_path  = "execution_state.log";
    bool        raw_stdout_only = false;

    for (int i = 1; i < argc; ++i) {
        if (strcmp(argv[i], "--raw-stdout") == 0) {
            raw_stdout_only = true;
        } else if (strcmp(argv[i], "--trace-log") == 0 && i + 1 < argc) {
            trace_log_path = argv[++i];
        } else if (strcmp(argv[i], "--trace-json") == 0 && i + 1 < argc) {
            trace_json_path = argv[++i];
        } else if (strcmp(argv[i], "--state-log") == 0 && i + 1 < argc) {
            state_log_path = argv[++i];
        }
    }

    ps2_cpu_ctx_t ctx;
    if (ps2_runtime_init(&ctx) != 0) {
        fprintf(stderr, "[host_real_runner] Failed to initialize PS2 runtime context\n");
        return 1;
    }

    int rc = ps2_init_guest_memory(&ctx);
    if (rc != 0) {
        fprintf(stderr, "[host_real_runner] Failed to initialize Guest Memory Image (rc=%d)\n", rc);
        ps2_runtime_destroy(&ctx);
        return 2;
    }

    /* Execute lifted code starting strictly at entry point 0x00100b20 (fn_00100b20___start) */
    int guest_exit_code = ps2_runtime_execute(&ctx, fn_00100b20___start);

    /* Write Syscall & Boundary Traces + Execution State Log */
    (void)ps2_write_syscall_trace_log(&ctx, trace_log_path);
    (void)ps2_write_syscall_trace_json(&ctx, trace_json_path);

    FILE *sfp = fopen(state_log_path, "w");
    if (sfp) {
        ps2_dump_execution_state(&ctx, sfp);
        fclose(sfp);
    }

    if (!raw_stdout_only) {
        printf("\n");
        ps2_dump_execution_state(&ctx, stdout);
        printf("Guest Output Literal (%zu bytes): \"", ctx.stdout_len);
        for (size_t i = 0; i < ctx.stdout_len; ++i) {
            unsigned char c = (unsigned char)ctx.stdout_buf[i];
            if (c == '\n') {
                printf("\\n");
            } else if (c >= 32 && c < 127) {
                putchar((int)c);
            } else {
                printf("\\x%02x", c);
            }
        }
        printf("\"\n");
        printf("Guest Output Bytes (Hex)       :");
        for (size_t i = 0; i < ctx.stdout_len; ++i) {
            printf(" %02x", (unsigned char)ctx.stdout_buf[i]);
        }
        printf("\n");
        printf("Syscall Breakdown              : total=%" PRIu64 " (مرفوعة أصلًا=%u, جذع خدمة=%u, معترضة عند الحدود=%u)\n",
               ctx.syscalls_dispatched,
               ctx.syscall_lifted_native_count,
               ctx.syscall_service_stub_count,
               ctx.syscall_boundary_intercept_count);
        printf("Indirect Dispatches            : total=%u (resolved to lifted functions=%u)\n",
               ctx.indirect_dispatches, ctx.indirect_lifted_resolved_count);
        printf("Trace Files Written            : %s, %s, %s\n",
               trace_log_path, trace_json_path, state_log_path);
    }

    ps2_runtime_destroy(&ctx);
    return guest_exit_code;
}
