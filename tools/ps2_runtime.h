/* FCSR (FCR31) architectural bit masks on R5900 COP1 */
#define PS2_FCSR_COND_BIT         (1U << 23) /* Condition bit C */
#define PS2_FCSR_FS_BIT           (1U << 24) /* Flush denormals to zero (always 1 on EE) */
#define PS2_FCSR_CAUSE_I          (1U << 17) /* Invalid operation cause */
#define PS2_FCSR_CAUSE_O          (1U << 16) /* Overflow cause */
#define PS2_FCSR_CAUSE_U          (1U << 15) /* Underflow cause */
#define PS2_FCSR_CAUSE_D          (1U << 14) /* Division by zero cause */
#define PS2_FCSR_STICKY_I         (1U << 6)  /* Sticky Invalid */
#define PS2_FCSR_STICKY_O         (1U << 5)  /* Sticky Overflow */
#define PS2_FCSR_STICKY_U         (1U << 4)  /* Sticky Underflow */
#define PS2_FCSR_STICKY_D         (1U << 3)  /* Sticky Divide-by-zero */

