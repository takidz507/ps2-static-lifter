/*
 * ps2_runtime.h — Milestone 2.3 PS2 Emotion Engine (R5900) Runtime, COP1 FPU & GS Boundary Library
 * =================================================================================================
 * Extends Milestone 2.2 (`ps2_runtime.h`) with Milestone 2.3 capabilities:
 *   1. Complete R5900 COP1 Single-Precision FPU Context & Helpers (Part 2):
 *      - 32 x 32-bit FPU registers (`fpr[32]`), 32-bit accumulator (`fpu_acc`), `fcr0` (0x00002e00),
 *        and `fcsr` (`FCR31`, with Condition bit `C` at bit 23 `0x00800000` and sticky/cause flags).
 *      - Hardware-accurate R5900 EE FPU semantics:
 *          * Input & output denormals (`exp == 0`) flushed to signed zero (`±0.0f`).
 *          * Exponent `255` (`0xFF`) treated as finite extended range (no IEEE-754 Inf/NaN),
 *            saturating on overflow to `±MAX` (`0x7FFFFFFF` / `0xFFFFFFFF`) and setting `FCSR.O`/`SO`.
 *          * Round-to-Zero (`RTZ` / truncation) arithmetic for `ADD.S`, `SUB.S`, `MUL.S`, `DIV.S`,
 *            `SQRT.S`, `RSQRT.S`, `ADDA.S`, `SUBA.S`, `MULA.S`, `MADD.S`, `MSUB.S`, `MADDA.S`,
 *            `MSUBA.S`, `CVT.W.S`, `CVT.S.W`.
 *          * Raw bit-preserving semantics for `MOV.S`, `ABS.S`, `NEG.S`, `MFC1`, `MTC1`, `LWC1`, `SWC1`.
 *   2. COP0 Condition Branch (`BC0T` / `BC0F`) & R5900 MMI3 `PCPYH` Support (Part 2).
 *   3. Declared Graphics Synthesizer (GS) & GIF DMA Channel 2 Boundary Model (Part 3):
 *      - Models EE DMAC Channel 2 (`0x1000A000..0x1000A080`), `D_STAT` (`0x1000E010`), `D_PCR` (`0x1000E020`),
 *        and GS Privileged Registers (`PMODE`, `DISPFB1`, `DISPLAY1`, `DISPFB2`, `DISPLAY2`, `BGCOLOR`, `CSR`
 *        at `0x12000000..0x12001000`).
 *      - Parses GIF packets in `PACKED` (`0`), `REGLIST` (`1`), and `IMAGE` (`2`) modes, updating
 *        GS internal registers (`PRIM`, `RGBAQ`, `XYZ2`, `XYOFFSET_1/2`, `FRAME_1/2`, `ZBUF_1/2`,
 *        `SCISSOR_1/2`, `PRMODECONT`, `PRMODE`, `TEST_1/2`, `FINISH`) and rasterizing into the
 *        guest-visible 4 MB GS VRAM (`PSMCT32` / `PSMCT24` / `PSMCT16`).
 *      - Implements `FRAME_LIMIT` harness termination when the guest completes N full frames via
 *        its own `graph_wait_vsync` (`GS_CSR` `VSINT` bit 3) path.
 */

