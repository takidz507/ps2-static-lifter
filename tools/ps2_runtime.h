/* Called when instruction budget is exhausted */
void ps2_on_budget_exceeded(ps2_cpu_ctx_t *ctx, uint32_t pc);

/* Per-instruction / per-delay-slot-pair PC ring tracker, gate detector & budget guard */
static inline void ps2_step_pc(ps2_cpu_ctx_t *ctx, uint32_t pc, uint32_t n_insns) {
    ctx->pc = pc;
    ctx->pc_ring[ctx->pc_ring_head] = pc;
    ctx->pc_ring_head = (ctx->pc_ring_head + 1U) % PS2_PC_RING_CAP;
    if (ctx->pc_ring_count < PS2_PC_RING_CAP) {
        ctx->pc_ring_count++;
    }

    if (pc == 0x00100000U && ctx->g1_crt0_bss_done_insns == 0ULL) {
        ctx->g1_crt0_bss_done_insns = ctx->insn_retired;
    } else if (pc == 0x0010004cU && !ctx->g1_passed) {
        ctx->g1_passed = true;
        ctx->g1_insn_count = ctx->insn_retired;
    }
    if ((pc == 0x0011d540U || pc == 0x00121870U) && !ctx->g2_passed) {
        ctx->g2_passed = true;
        ctx->g2_insn_count = ctx->insn_retired;
    }

    ctx->insn_retired += (uint64_t)n_insns;
    if (ctx->insn_budget > 0ULL && ctx->insn_retired >= ctx->insn_budget) {
        ps2_on_budget_exceeded(ctx, pc);
    }
}

